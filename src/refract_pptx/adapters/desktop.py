def _vm_sha256(env: Any, path: str) -> str:
    quoted = shlex.quote(path)
    output = _vm_command(
        env,
        f"if [ -f {{quoted}} ]; then sha256sum {{quoted}} | cut -d' ' -f1; "
        "else echo MISSING; fi",
        30,
    ).strip()
    if not output:
        raise RuntimeError("the runner returned no result for a VM filesystem check")
    value = output.splitlines()[-1]
    return "" if value == "MISSING" else value


def _persist_candidate(env: Any) -> dict[str, Any]:
    before = _vm_sha256(env, DECK_VM_PATH)
    evidence: dict[str, Any] = {{
        "disk_sha_before": before,
        "save_attempted": False,
    }}
    if before == INIT_SHA256:
        window = shlex.quote(DECK_NAME)
        script = (
            "export DISPLAY=${{DISPLAY:-:0}}; "
            f"if command -v xdotool >/dev/null 2>&1 && "
            f"xdotool search --name {{window}} windowactivate --sync >/dev/null 2>&1; then "
            "xdotool key ctrl+s; "
            "else python3 -c \\\"import pyautogui; pyautogui.hotkey('ctrl','s')\\\"; fi; "
            "sleep 4"
        )
        _vm_command(env, script, 30)
        evidence["save_attempted"] = True
    _vm_command(
        env,
        "pkill -f wpp || true; pkill -f wps || true; pkill -f soffice || true",
        30,
    )
    time.sleep(1)
    after = _vm_sha256(env, DECK_VM_PATH)
    evidence["disk_sha_after"] = after
    evidence["disk_changed"] = bool(after and after != INIT_SHA256)
    return evidence


def _scan_save_as(env: Any) -> tuple[list[tuple[str, str]], str]:
    stamp = shlex.quote(SETUP_STAMP)
    desktop = shlex.quote(DESKTOP_DIR)
    output = _vm_command(
        env,
        f"if [ ! -e {{stamp}} ]; then echo NO_STAMP; exit 0; fi; echo SCAN_READY; "
        f"find {{desktop}} /home/user -maxdepth 3 -type f -name '*.pptx' "
        f"-newer {{stamp}} -not -path {{shlex.quote(DECK_VM_PATH)}} -print0 2>/dev/null "
        "| xargs -0 -r sha256sum 2>/dev/null",
        60,
    )
    if not output.strip():
        raise RuntimeError("the runner returned no result for Save As discovery")
    if output.strip() == "NO_STAMP":
        return [], "setup stamp is missing; Save As recovery was not attempted"
    found: list[tuple[str, str]] = []
    seen: set[str] = set()
    for line in output.splitlines():
        if line.strip() == "SCAN_READY":
            continue
        digest, _, path = line.strip().partition(" ")
        path = path.strip()
        if len(digest) == 64 and path and path not in seen:
            seen.add(path)
            if digest != INIT_SHA256 and digest not in SUPPLIED_PPTX_SHA256:
                found.append((path, digest))
    return found, ""


def _candidate_file(env: Any, evidence: dict[str, Any]) -> tuple[str, str]:
    pinned_sha = evidence.get("disk_sha_after", "")
    if pinned_sha and pinned_sha != INIT_SHA256:
        local = get_vm_file(
            env, {{"path": DECK_VM_PATH, "dest": f"task_{{TASK_ID}}_result.pptx"}}
        )
        if not local or not os.path.isfile(local):
            raise RuntimeError(
                "the VM reported a changed result but the runner could not retrieve it"
            )
        return str(local), DECK_VM_PATH
    found, note = _scan_save_as(env)
    if note:
        evidence["save_as_note"] = note
    evidence["save_as_candidates"] = [path for path, _ in found]
    if len(found) != 1:
        return "", ""
    vm_path = found[0][0]
    local = get_vm_file(
        env, {{"path": vm_path, "dest": f"task_{{TASK_ID}}_save_as_result.pptx"}}
    )
    if not local or not os.path.isfile(local):
        raise RuntimeError("a unique Save As result was found but could not be retrieved")
    return str(local), vm_path


