def _asset_url(remote_path: str) -> str:
    base = (os.environ.get(ASSET_BASE_ENV) or ASSET_BASE_URL).rstrip("/")
    if "://" not in base:
        return os.path.join(base, *remote_path.split("/"))
    quoted = "/".join(urllib.parse.quote(item, safe="") for item in remote_path.split("/"))
    return f"{{base}}/{{quoted}}"


