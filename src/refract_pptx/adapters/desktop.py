def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def _safe_relative(value: str, label: str) -> PurePosixPath:
    path = PurePosixPath(value.replace("\\", "/"))
    if path.is_absolute() or not path.parts or ".." in path.parts:
        raise AdapterError(f"{label} must stay inside its declared root: {value}")
    return path


def _copy_file(source: Path, target: Path) -> None:
    if source.is_symlink():
        raise AdapterError(f"symbolic links are not allowed in deployment assets: {source}")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)


@contextmanager
def _staging_directory(target: Path):
    staging = target.parent / f".{target.name}-{uuid4().hex}"
    staging.mkdir()
    try:
        yield staging
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)


def _runtime_archive(target: Path) -> None:
    package_root = Path(__file__).resolve().parents[1]
    target.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for relative in _RUNTIME_FILES:
            source = package_root / relative
            if not source.is_file():
                raise AdapterError(f"runtime source is missing: {source}")
            payload = source.read_text(encoding="utf-8").replace("refract_pptx", "_refract_runtime")
            info = zipfile.ZipInfo(f"_refract_runtime/{relative}")
            info.date_time = (1980, 1, 1, 0, 0, 0)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, payload.encode("utf-8"))


